public class Pessoa {
    private String nome;
    private String cpf;
    private int idade;
    private float altura;
    private float peso;
}

public Pessoa(String nome, String cpf, int idade, float altura, float peso) {
    this.nome = nome;
    this.cpf = cpf;
    this.idade = idade;
    this.altura = altura;
    this.peso = peso;
}
